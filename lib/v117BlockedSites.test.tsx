/** AWS WAF's JavaScript challenge, trimmed from the real Rainbow Records response. */
const AWS_WAF_CHALLENGE = `<!DOCTYPE html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1"><title></title>
<script type="text/javascript">window.awsWafCookieDomainList = []; window.gokuProps = {"key":"AQID","iv":"EkQS","context":"ZOqB"};</script>
<script src="https://9da6f8cefaad.0e3eea1d.us-east-2.token.awswaf.com/9da6f8cefaad/4851a1363802/66d12f9847b3/challenge.js"></script>
</head><body><div id="challenge-container"></div>
<script type="text/javascript">AwsWafIntegration.saveReferrer();</script></body></html>`;

/** CloudFront's block page, as a headless browser with our user agent received it. */
const CLOUDFRONT_BLOCK = `<HTML><HEAD><TITLE>ERROR: The request could not be satisfied</TITLE></HEAD><BODY>
<H1>403 ERROR</H1><H2>The request could not be satisfied.</H2>Request blocked.
<PRE>Generated by cloudfront (CloudFront)
Request ID: abc==</PRE></BODY></HTML>`;

const htmlResponse = (status: number, html: string, url = "https://example.com/") =>
  ({
    ok: status >= 200 && status < 300,
    status,
    url,
    headers: new Headers({ "content-type": "text/html" }),
    text: async () => html,
    arrayBuffer: async () => new TextEncoder().encode(html).buffer,
  }) as unknown as Response;

describe("challenge pages are detected at any status, 2xx included", () => {
  test("AWS WAF's challenge and CloudFront's block page", () => {
    expect(looksLikeBotChallenge(AWS_WAF_CHALLENGE)).toBe(true);
    expect(looksLikeBotChallenge(CLOUDFRONT_BLOCK)).toBe(true);
  });

  test("a generic phrase counts only on a small page — never on a real page that happens to say it", () => {
    expect(looksLikeBotChallenge("<html><title>Just a moment...</title><body>Checking your browser</body></html>")).toBe(true);
    const realPage = `<html><title>Our café</title><body><h1>Welcome</h1><p>Just a moment from the station.</p><p>${"We bake bread every morning. ".repeat(80)}</p></body></html>`;
    expect(looksLikeBotChallenge(realPage)).toBe(false);
  });

  test("THE BUG: the homepage fetch gets a 202 challenge — a block, never the homepage", async () => {
    const fetchImpl = vi.fn(async () => htmlResponse(202, AWS_WAF_CHALLENGE)) as unknown as typeof fetch;
    const result = await fetchWebsiteHtml("http://www.rainbowrecordsde.com/", fetchImpl);
    expect(result.html).toBeNull();
    expect(result.failureReason).toBe("blocked_automated_check");
  });

  test("a real 200 page is still read", async () => {
    const fetchImpl = vi.fn(async () => htmlResponse(200, "<html><title>Rainbow Records</title><body><h1>Records</h1></body></html>")) as unknown as typeof fetch;
    const result = await fetchWebsiteHtml("rainbowrecordsde.com", fetchImpl);
    expect(result.html).toContain("Rainbow Records");
    expect(result.failureReason).toBeNull();
  });

  test("a browser render that comes back as CloudFront's block page is blocked, not ok", async () => {
    const fetchImpl = vi.fn(async () => htmlResponse(200, CLOUDFRONT_BLOCK)) as unknown as typeof fetch;
    const out = await renderPageHtml("https://www.rainbowrecordsde.com/", "key", fetchImpl);
    expect(out.kind).toBe("blocked");
  });
});

describe("empty-page guard (on the content we actually read)", () => {
  const empty = {
    hasTitle: false,
    hasMetaDescription: false,
    hasViewportTag: true,
    headingCount: 0,
    visibleTextLength: 0,
    hasPhoneLink: false,
    hasEmailLink: false,
    hasContactPageLink: false,
    hasCtaText: false,
    socialProfiles: [],
    isLikelyClientRenderedShell: false,
    renderedContentSignals: null,
  } as unknown as WebsiteContentSignals;

  test("no title, headings, text or contact links: couldn't read", () => {
    expect(isUnreadablePage(empty)).toBe(true);
  });
  test("anything real on it, or a JavaScript-built shell (read another way): still analyzed", () => {
    expect(isUnreadablePage({ ...empty, hasTitle: true })).toBe(false);
    expect(isUnreadablePage({ ...empty, headingCount: 2 })).toBe(false);
    expect(isUnreadablePage({ ...empty, visibleTextLength: 400 })).toBe(false);
    expect(isUnreadablePage({ ...empty, hasEmailLink: true })).toBe(false);
    expect(isUnreadablePage({ ...empty, isLikelyClientRenderedShell: true })).toBe(false);
  });
});

describe("HTTPS: any real answer over https:// proves it", () => {
  test("a bot block's 403 over https:// is HTTPS working", async () => {
    const fetchImpl = vi.fn(async () => htmlResponse(403, CLOUDFRONT_BLOCK, "https://www.rainbowrecordsde.com/")) as unknown as typeof fetch;
    expect(await checkWebsiteHttps("http://www.rainbowrecordsde.com/", fetchImpl)).toEqual({ status: "https", reason: null });
    expect(fetchImpl).toHaveBeenCalledTimes(1);
  });

  test("an http:// request redirected to an https:// 202 challenge counts too", async () => {
    const fetchImpl = vi
      .fn()
      .mockRejectedValueOnce(new TypeError("fetch failed"))
      .mockResolvedValueOnce(htmlResponse(202, AWS_WAF_CHALLENGE, "https://example.com/")) as unknown as typeof fetch;
    expect(await checkWebsiteHttps("example.com", fetchImpl)).toEqual({ status: "https", reason: null });
  });

  test("a block that never answered over https:// still couldn't verify", async () => {
    const fetchImpl = vi.fn(async () => htmlResponse(403, CLOUDFRONT_BLOCK, "http://example.com/")) as unknown as typeof fetch;
    expect(await checkWebsiteHttps("http://example.com", fetchImpl)).toEqual({ status: "unreachable", reason: "blocked_automated_check" });
  });

  test("a timeout is retried before saying couldn't verify", async () => {
    const abort = Object.assign(new Error("aborted"), { name: "AbortError" });
    const fetchImpl = vi.fn().mockRejectedValueOnce(abort).mockResolvedValueOnce(htmlResponse(200, "<html></html>", "https://example.com/")) as unknown as typeof fetch;
    expect(await checkWebsiteHttps("example.com", fetchImpl)).toEqual({ status: "https", reason: null });
    expect(fetchImpl).toHaveBeenCalledTimes(2);
  });
});

const check = (id: string, earned: number | null, max = 1, extra: Partial<CheckResult> = {}): CheckResult => ({
  id,
  label: id,
  category: id.startsWith("website.") ? "website" : "visibility",
  maxPoints: max,
  earnedPoints: earned,
  confidence: earned === null ? "NOT_FOUND" : "VERIFIED",
  explanation: "",
  meta: null,
  ...(earned === null ? { excludedReason: "unreachable" as const } : {}),
  ...extra,
});

/** Rainbow Records after the fix: HTTPS and speed checked, the rest couldn't run. */
const blockedSite = [
  check("visibility.rating", 10, 14),
  check("website.has_website", 4, 4),
  check("website.https", 5, 5),
  check("website.performance_mobile", 3, 3),
  ...["content_depth", "contact_conversion", "mobile_friendly", "about_presence", "services_presence", "social_links", "security", "links"].map((id) => check(`website.${id}`, null)),
];
const website = (checks: CheckResult[], version = SCORING_VERSION) => breakdownFromChecks(checks, "en", version).categories.find((c) => c.id === "website")!;

describe("the 1.17.0 cap: more than half of the website checks couldn't run", () => {
  test("SCORING_VERSION is 1.17.0", () => {
    expect(SCORING_VERSION).toBe("1.18.0");
  });

  test("Partly checked: at most 80% of the points it could check", () => {
    const w = website(blockedSite);
    expect(w.partlyChecked).toBe(true);
    expect(w.possiblePoints).toBe(12);
    expect(w.earnedPoints).toBeCloseTo(12 * PARTLY_CHECKED_CAP);
    expect(w.relativeScore).toBeCloseTo(80);
  });

  test("lowers the total; 1.16.0 had no cap", () => {
    expect(breakdownFromChecks(blockedSite, "en", "1.17.0").total).toBeLessThan(breakdownFromChecks(blockedSite, "en", "1.16.0").total);
    expect(website(blockedSite, "1.16.0").partlyChecked).toBeUndefined();
  });

  test("a site already under 80% keeps its own points", () => {
    const low = blockedSite.map((c) => (c.id === "website.https" ? { ...c, earnedPoints: 0 } : c.id === "website.performance_mobile" ? { ...c, earnedPoints: 0 } : c));
    expect(website(low).earnedPoints).toBe(4);
  });

  test("half or fewer couldn't run: no cap", () => {
    const mostlyChecked = blockedSite.map((c, i) => (c.earnedPoints === null && i % 2 === 0 ? { ...c, earnedPoints: 1, confidence: "VERIFIED" as const, excludedReason: undefined } : c));
    expect(websiteMostlyUnchecked(mostlyChecked.filter((c) => c.category === "website"))).toBe(false);
    expect(website(mostlyChecked).partlyChecked).toBeUndefined();
  });

  test("never for a business with no website, a site not checked yet, or a speed test waiting for a second run", () => {
    const noWebsite = blockedSite.map((c) => (c.id === "website.has_website" ? { ...c, earnedPoints: 0 } : c));
    expect(website(noWebsite).partlyChecked).toBeUndefined();
    const notCheckedYet = blockedSite.map((c) => (c.earnedPoints === null ? { ...c, excludedReason: "not_checked_yet" as const } : c));
    expect(website(notCheckedYet).partlyChecked).toBeUndefined();
    const fourChecked = [check("website.has_website", 4, 4), check("website.https", 5, 5), check("website.security", 2, 2), check("website.links", 2, 2)];
    const waiting = [...fourChecked, check("website.performance_mobile", null, 3, { meta: { noScoreCause: "one_test" }, excludedReason: undefined }), check("website.content_depth", null, 5), check("website.contact_conversion", null, 3), check("website.about_presence", null, 1)];
    expect(website(waiting).partlyChecked).toBeUndefined();
  });

  test("a 1.16.0 or 1.15.0 scan stands for 1.17.0 unless the cap applies", () => {
    const now = (partlyChecked: boolean) => ({ scoringVersion: "1.17.0", checks: [], categories: [{ id: "website", partlyChecked }] }) as never;
    expect(savedVersionStandsIn("1.16.0", now(false))).toBe(true);
    expect(savedVersionStandsIn("1.15.0", now(false))).toBe(true);
    expect(savedVersionStandsIn("1.16.0", now(true))).toBe(false);
    expect(savedVersionStandsIn("1.14.0", now(false))).toBe(false);
  });
});

describe("Partly checked note and the allow-PostScoreBot step (EN + ES)", () => {
  const category = (extra: Partial<CategoryResult>): CategoryResult => ({ ...website(blockedSite), ...extra });
  const render = (c: CategoryResult, locale: "en" | "es") =>
    renderToStaticMarkup(
      <LocaleProvider locale={locale}>
        <WebsiteCoverageNote category={c} hasWebsite />
      </LocaleProvider>
    ).replace(/&#x27;/g, "'");

  test("a blocked site: the pill, the 80% line and the note", () => {
    const en = render(category({ blocksAutomatedChecks: true }), "en");
    expect(en).toContain("Partly checked");
    expect(en).toContain("at most 80% of its points");
    expect(en).toContain("Your website's security blocks automated checks, so we could only check part of it. Ask your web person to allow PostScoreBot to see your full score.");
    const es = render(category({ blocksAutomatedChecks: true }), "es");
    expect(es).toContain("Revisado en parte");
    expect(es).toContain("como máximo el 80% de sus puntos");
    expect(es).toContain("Pídale a la persona que administra su sitio web que permita el acceso a PostScoreBot");
  });

  test("partly checked for another reason (timeouts): no blocked note", () => {
    const en = render(category({ blocksAutomatedChecks: undefined }), "en");
    expect(en).toContain("Partly checked");
    expect(en).not.toContain("PostScoreBot");
  });

  test("the setup step: no points, how-to steps, real help links", () => {
    const en = buildAllowBotStep("en");
    expect(en.checkId).toBe(ALLOW_BOT_STEP_ID);
    expect(en.effort).toBe("setup");
    expect(en.promisedPoints).toBe(0);
    expect(en.fix).toContain("Cloudflare");
    expect(en.fix).toContain("AWS WAF");
    expect(en.fix).toContain("Bot Fight Mode");
    expect((en.links ?? []).map((l) => l.href)).toEqual([
      "https://developers.cloudflare.com/waf/custom-rules/",
      "https://docs.aws.amazon.com/waf/latest/developerguide/waf-rule-statement-type-string-match.html",
    ]);
    const es = buildAllowBotStep("es");
    expect(es.label).toBe("Permita que PostScore revise todo su sitio web");
    expect(es.fix).toContain("Pídale");
  });
});

describe("HTTPS wording for a site that blocks automated checks (EN + ES)", () => {
  const https = CHECKS.find((c) => c.id === "website.https")!;
  const input = (blocked: boolean) =>
    ({ website: "https://www.rainbowrecordsde.com/", httpsStatus: "https", websiteAnalysis: { contentFetchFailureReason: blocked ? "blocked_automated_check" : null } }) as never;
  test("answered securely, never \"loads\" — same points", () => {
    expect(https.evaluate(input(true), "en")).toMatchObject({ earnedPoints: 5, explanation: "The site answered securely over HTTPS (its security blocked our full check)." });
    expect(https.evaluate(input(true), "es").explanation).toBe("El sitio respondió de forma segura por HTTPS (su seguridad bloqueó nuestra revisión completa).");
    expect(https.evaluate(input(false), "en").explanation).not.toContain("blocked");
  });
});
